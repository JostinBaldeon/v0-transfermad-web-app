export function getClubById(id: string): Club | undefined {
  return clubs.find((club) => club.id === id)
}

export function getClubsByLeague(league: "mad-league-1" | "mad-league-2"): Club[] {
  return clubs.filter((club) => club.league === league)
}

export function getTotalMarketValue(): number {
  return clubs.reduce((sum, club) => sum + club.marketValue, 0)
}

export function formatMarketValue(value: number): string {
  if (value >= 1000) {
    return `${(value / 1000).toFixed(2).replace(".", ",")} mil mill. €`
  }
  return `${value.toFixed(2).replace(".", ",")} mill. €`
}

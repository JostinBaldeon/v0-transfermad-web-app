export function getPlayerById(id: string): Player | undefined {
  return players.find((player) => player.id === id)
}

export function getPlayersByClub(clubId: string): Player[] {
  return players.filter((player) => player.clubId === clubId)
}

export function getLegends(): Player[] {
  return players.filter((player) => player.isLegend)
}

export function searchPlayers(query: string): Player[] {
  const searchTerm = query.toLowerCase()
  return players.filter(
    (player) =>
      player.name.toLowerCase().includes(searchTerm) ||
      player.firstName.toLowerCase().includes(searchTerm) ||
      player.lastName.toLowerCase().includes(searchTerm)
  )
}

export function getPositionName(position: Position): string {
  const positions: Record<Position, string> = {
    POR: "Portero",
    DFC: "Defensa Central",
    LI: "Lateral Izquierdo",
    LD: "Lateral Derecho",
    MCD: "Mediocentro Defensivo",
    MC: "Mediocentro",
    MCO: "Mediocentro Ofensivo",
    EI: "Extremo Izquierdo",
    ED: "Extremo Derecho",
    SD: "Segundo Delantero",
    DC: "Delantero Centro",
  }
  return positions[position]
}

export function formatMarketValue(value: number): string {
  if (value >= 1000) {
    return `${(value / 1000).toFixed(2).replace(".", ",")} mil mill. €`
  }
  return `${value.toFixed(2).replace(".", ",")} mill. €`
}
